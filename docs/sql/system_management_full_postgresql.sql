DROP VIEW IF EXISTS V_DICT;

CREATE VIEW V_DICT AS
SELECT TYPE AS CODE,
       NAME,
       COALESCE(VALUE, CODE) AS D_CODE,
       NAME AS D_VALUE,
       FROZEN,
       SORT
FROM SYS_DICT
WHERE DELETED = 0
  AND ISLEAF = TRUE
  AND TYPE IS NOT NULL
  AND (FROZEN IS NULL OR FROZEN != 1);

DROP VIEW IF EXISTS V_GRANTED_MODULE;
DROP VIEW IF EXISTS SYS_ROLE_MODULE;

-- 兼容旧 Mapper 的角色-模块关系视图；真实授权数据来自 SYS_ROLERES_REF。
CREATE VIEW SYS_ROLE_MODULE AS
SELECT rr.ROLE_ID,
       mr.MAIN_ID AS MODULE_ID,
       rr.RESOURCE_ID
FROM SYS_ROLERES_REF rr
    JOIN SYS_MODULE_RESOURCES mr ON rr.RESOURCE_ID = mr.ID
WHERE mr.DELETED = 0;

CREATE VIEW V_GRANTED_MODULE AS
SELECT m.ID,
       m.REVISION,
       m.TENANT_ID,
       m.CODE,
       m.NAME,
       m.ICON,
       m.ROUTE_URL,
       m.COMPONENT_URL,
       m.PID,
       m.PATH,
       m.ISLEAF,
       m.SORT,
       m.FROZEN,
       m.DELETED,
       m.REMARK,
       m.CREATE_ID,
       m.CREATE_BY,
       m.UTC_CREATE,
       m.MODIFY_ID,
       m.MODIFY_BY,
       m.UTC_MODIFY,
       r.CODE AS ROLE_CODE,
       r.ID AS ROLE_ID
FROM SYS_MODULE m
    JOIN SYS_ROLE_MODULE rm ON m.ID = rm.MODULE_ID
    JOIN SYS_ROLE r ON rm.ROLE_ID = r.ID
WHERE m.DELETED = 0
  AND r.DELETED = 0;

