CREATE TABLE IF NOT EXISTS EVA_TENANT_SCHEMA_VERSION (
    VERSION VARCHAR(50) PRIMARY KEY,
    INSTALLED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO EVA_TENANT_SCHEMA_VERSION(VERSION)
